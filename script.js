let currentLang = 'pt';

function applyTranslations(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = i18n[lang] && i18n[lang][key];
    if (value === undefined) return;

    if (key === 'hero.title') {
      el.innerHTML = value;
      el.setAttribute('data-text', i18n[lang]['hero.titlePlain'] || value.replace(/<[^>]+>/g, ''));
    } else {
      el.innerHTML = value;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const value = i18n[lang] && i18n[lang][key];
    if (value !== undefined) el.setAttribute('placeholder', value);
  });

  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    const value = i18n[lang] && i18n[lang][key];
    if (value !== undefined) {
      el.setAttribute('aria-label', value);
      el.setAttribute('title', value);
    }
  });

  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
  document.querySelectorAll('.lang-label').forEach(el => {
    el.textContent = lang === 'pt' ? 'EN' : 'PT';
  });
}

function setLanguage(lang) {
  currentLang = lang;
  try { localStorage.setItem('lustosaLang', lang); } catch (e) { }
  applyTranslations(lang);
}

(function initLanguage() {
  let saved = null;
  try { saved = localStorage.getItem('lustosaLang'); } catch (e) { }
  const browserLang = (navigator.language || '').toLowerCase().startsWith('pt') ? 'pt' : 'en';
  currentLang = saved || browserLang;
  applyTranslations(currentLang);
})();

document.querySelectorAll('#langToggle, #langToggleMobile').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(currentLang === 'pt' ? 'en' : 'pt'));
});

