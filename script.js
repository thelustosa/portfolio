// ---------- Boot screen ----------
(function bootScreen() {
  const screen = document.getElementById('bootScreen');
  const log = document.getElementById('bootLog');
  if (!screen || !log) return;

  // já viu o boot nessa sessão? pula direto
  if (sessionStorage.getItem('lustosaBootSeen')) {
    screen.classList.add('hide');
    setTimeout(() => screen.remove(), 500);
    window.dispatchEvent(new Event('bootDone'));
    return;
  }

  if (prefersReducedMotion) {
    screen.remove();
    sessionStorage.setItem('lustosaBootSeen', '1');
    window.dispatchEvent(new Event('bootDone'));
    return;
  }

  const bootLines = [
    '> inicializando lustosa.dev...',
    '> carregando módulos: frontend [ok] backend [ok] segurança [ok]',
    '> verificando integridade dos sistemas...',
    '> estabelecendo conexão segura...',
    '> acesso concedido.',
  ];

  let i = 0;
  function nextLine() {
    if (i >= bootLines.length) {
      setTimeout(() => {
        screen.classList.add('hide');
        sessionStorage.setItem('lustosaBootSeen', '1');
        window.dispatchEvent(new Event('bootDone'));
        setTimeout(() => screen.remove(), 500);
      }, 400);
      return;
    }
    const div = document.createElement('div');
    div.className = 'line' + (i === bootLines.length - 1 ? ' ok' : '');
    div.textContent = bootLines[i];
    log.appendChild(div);
    i++;
    setTimeout(nextLine, 260);
  }
  nextLine();
})();

