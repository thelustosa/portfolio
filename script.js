(function contactFadeIn() {
  const grid = document.querySelector('.contact-grid');
  if (!grid) return;
  if (prefersReducedMotion) {
    grid.classList.add('is-visible');
    return;
  }
  function check() {
    if (!grid.classList.contains('is-visible') && elementNearViewport(grid)) {
      grid.classList.add('is-visible');
    }
  }
  check();
  window.addEventListener('scroll', check);
  window.addEventListener('resize', check);
})();

// ---------- Parallax leve no card da hero ----------
if (!prefersReducedMotion) {
  const parallaxTarget = document.querySelector('.status-card');
  let ticking = false;

  window.addEventListener('scroll', () => {
    if (ticking) return;
    ticking = true;
    requestAnimationFrame(() => {
      if (parallaxTarget) {
        const offset = window.scrollY;
        // só aplica enquanto a hero estiver visível, movimento sutil
        const shift = Math.min(offset * 0.12, 60);
        parallaxTarget.style.transform = `translateY(${shift}px)`;
      }
      ticking = false;
    });
  });
}

(function floatingParticles() {
  const canvas = document.getElementById('particlesCanvas');
  if (!canvas || prefersReducedMotion) return;

  const ctx = canvas.getContext('2d');
  const isMobile = window.matchMedia('(max-width: 700px)').matches;
  const COUNT = isMobile ? 22 : 46;

  let width, height, particles, raf, running = false;

  function makeParticle() {
    return {
      x: Math.random() * width,
      y: Math.random() * height,
      r: Math.random() * 1.6 + 0.6,
      speed: Math.random() * 0.25 + 0.08,
      drift: (Math.random() - 0.5) * 0.15,
      alpha: Math.random() * 0.35 + 0.12,
    };
  }

  function init() {
    width = canvas.width = window.innerWidth;
    height = canvas.height = window.innerHeight;
    particles = Array.from({ length: COUNT }, makeParticle);
  }

  function tick() {
    ctx.clearRect(0, 0, width, height);
    particles.forEach(p => {
      p.y -= p.speed;
      p.x += p.drift;

      if (p.y < -10) { p.y = height + 10; p.x = Math.random() * width; }
      if (p.x < -10) p.x = width + 10;
      if (p.x > width + 10) p.x = -10;

      ctx.beginPath();
      ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
      ctx.fillStyle = `rgba(201, 243, 29, ${p.alpha})`;
      ctx.fill();
    });
    if (running) raf = requestAnimationFrame(tick);
  }

  function start() {
    if (running) return;
    running = true;
    raf = requestAnimationFrame(tick);
  }
  function stop() {
    running = false;
    cancelAnimationFrame(raf);
  }

  init();
  start();

  window.addEventListener('resize', init);

  // pausa quando a aba não está visível — economiza CPU/bateria
  document.addEventListener('visibilitychange', () => {
    if (document.hidden) stop();
    else start();
  });
})();

